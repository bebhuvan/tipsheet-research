"""`desk report <slug>`: the study's public report, studies/<slug>/REPORT.md.

Two halves. The record (between the auto markers) is generated from the study's files and git history and
is rewritten every run: timeline, questions, amendments, checks, the recompute, the review and the
responses, models and costs, and what was tried. The narrative sections are written by the lead model (and
edited by the people on the study) and are kept as they are across runs. `desk check` wants every narrative
section filled in before a study counts as done.

The article is for readers; the report is for anyone who wants to know how the study was actually done,
including what went wrong.
"""

from __future__ import annotations

import json
import re

from .config import ROOT, read_json
from .models import spent_inr
from .study import Study, git

START, END = "<!-- auto:start -->", "<!-- auto:end -->"
TODO = "_To be written by the lead researcher._"
NARRATIVE = [
    ("What I set out to ask", "The big question, why it mattered, and how the sub-questions were chosen (which candidates were cut and why)."),
    ("What I found", "The answer to each sub-question, its answer type, and whether the prediction held."),
    ("What changed from the plan", "Every amendment and follow-up, and why. Say if a change came after seeing results."),
    ("Mistakes and how they were caught", "Bugs, wrong assumptions and data problems: what caught each (input check, recompute, review, a person) and what it changed."),
    ("Dead ends", "Analyses tried and dropped, and charts that didn't make the article, with the reason."),
    ("What a sceptical reader should check first", "The weakest link in the argument, and how to test it with the code here."),
    ("What the desk should change", "Lessons for the guides or the tooling. Copy any that are adopted into the guides."),
]


def _record(S: Study) -> str:
    out = [START, "", "## The record", "", "_Generated by `desk report` from the study's files and git history. Do not edit by hand._", ""]
    rel = S.dir.relative_to(ROOT).as_posix()
    log = git("log", "--reverse", "--format=%h %ad %s", "--date=short", "--", rel).strip().splitlines()
    tags = git("tag", "--list", f"{S.slug}/*").strip()
    out += ["### Timeline", ""]
    fz = S.freeze()
    out.append(f"- Plan frozen at `{fz['commit'][:7]}` on {fz['frozen_on']}." if fz else "- Plan not frozen yet.")
    out += [f"- Tag `{t}`" for t in tags.splitlines() if t]
    out += [f"- `{line}`" for line in log[-40:]]
    out += ["", "### Sub-questions", ""]
    for q in S.questions():
        out.append(f"- **{q.id.upper()}.** {q.title} (declared checks: {', '.join(q.checks) or 'none'})")
    amend = re.split(r"^## Amendments\b", S.plan, maxsplit=1, flags=re.M)
    out += ["", "### Amendments to the plan", "", amend[1].strip() if len(amend) > 1 else "None.", ""]

    R = S.results()
    if R:
        n_exp = sum(1 for v in R["facts"].values() if v.get("exploratory"))
        out += ["### Results", "", f"- Computed {R['computed_at']} from `compute.py` (sha256 `{R['compute_sha256'][:12]}`).",
                f"- {len(R['facts'])} facts, {n_exp} of them exploratory; {len(R.get('exploratory_tried', []))} exploratory variants tried.",
                "- Inputs:"]
        out += [f"  - `{k}`: {v['file']}, sha256 `{v['sha256'][:12]}`" for k, v in R["inputs"].items()]
        out += ["", "| Check | Passed | Detail |", "|---|---|---|"]
        out += [f"| {k} | {'yes' if v['passed'] else '**no**'} | {v['detail']} |" for k, v in R["checks"].items()]
        if R.get("exploratory_tried"):
            out += ["", "Exploratory variants tried:"] + [f"- {t}" for t in R["exploratory_tried"]]
        out.append("")

    rc = S.checks_dir / "recompute.json"
    if rc.is_file():
        r = read_json(rc)
        out += ["### Independent recompute", "", f"Model: {r['attempts'][-1]['model']}; {len(r['attempts'])} attempt(s). "
                "Its script is `checks/recompute_script.py`.", "", "| Fact | Ours | Theirs | Tolerance | Match |", "|---|---|---|---|---|"]
        out += [f"| {x['key']} | {x['ours']} | {x['theirs']} | {x['tolerance']} | {'yes' if x['match'] else '**no**'} |" for x in r["rows"]]
        if r.get("ambiguities"):
            out += ["", "Ambiguities the recomputing model resolved:"] + [f"- {a}" for a in r["ambiguities"]]
        out.append("")

    rv = S.checks_dir / "review.json"
    if rv.is_file():
        v = read_json(rv)
        rp = S.checks_dir / "responses.json"
        resp = read_json(rp) if rp.is_file() else {}
        out += ["### Review and cold read", "", f"Model: {v['model']}. Overall: {v.get('overall', '')}", "",
                "| Id | Severity | Problem | Response |", "|---|---|---|---|"]
        out += [f"| {i['id']} | {i['severity']} | {i['problem']} | {resp.get(i['id'], '_none_')} |" for i in v["issues"]]
        if v.get("answers"):
            out += ["", "The cold reader's answers to each sub-question, from the article alone:"]
            out += [f"- **{q}**: {a}" for q, a in v["answers"].items()]
        out.append("")

    ledger = S.checks_dir / "costs.jsonl"
    if ledger.is_file():
        rows = [json.loads(x) for x in ledger.read_text().splitlines() if x.strip()]
        out += ["### Model calls and cost", "", "| When | Role | Model | Tokens in / out | ₹ |", "|---|---|---|---|---|"]
        out += [f"| {x['at']} | {x['role']} | {x['model']} | {x['tokens_in']:,} / {x['tokens_out']:,} | {x['inr']:.2f} |" for x in rows]
        out += ["", f"Total: ₹{spent_inr(S.dir):.2f}. Every request and reply is in `checks/transcripts/`. "
                "The lead model's work (plan, code, article, this report) ran in an interactive session and is not metered here.", ""]

    st = S.checks_dir / "status.json"
    if st.is_file():
        s = read_json(st)
        out += ["### Last `desk check`", "", f"{s['at']}: " + ", ".join(f"{i['check']} {i['status']}" for i in s["items"]), ""]
    out.append(END)
    return "\n".join(out)


def narrative_missing(S: Study) -> list[str]:
    path = S.dir / "REPORT.md"
    if not path.is_file():
        return [h for h, _ in NARRATIVE]
    text = path.read_text().split(START)[0]
    missing = []
    for h, _ in NARRATIVE:
        m = re.search(rf"^## {re.escape(h)}\n(.*?)(?=^## |\Z)", text, flags=re.M | re.S)
        if not m or TODO in m.group(1) or len(m.group(1).split()) < 15:
            missing.append(h)
    return missing


def main(slug: str) -> int:
    S = Study(slug)
    path = S.dir / "REPORT.md"
    if path.is_file():
        head = path.read_text().split(START)[0].rstrip()
    else:
        head = "\n\n".join([f"# Study report: {slug}",
                            "How this study was actually done, written by the lead researcher (an AI model, edited by the people "
                            "on the study) when it finished. The reader-facing article is `article.mdx`; the frozen plan is `plan.md`."]
                           + [f"## {h}\n\n<!-- {hint} -->\n{TODO}" for h, hint in NARRATIVE])
    path.write_text(head + "\n\n" + _record(S) + "\n")
    miss = narrative_missing(S)
    print(f"wrote {path.relative_to(ROOT)}" + (f"; to write: {', '.join(miss)}" if miss else "; narrative complete"))
    return 0
